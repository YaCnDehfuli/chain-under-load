"""Measure the rule set across the chain, and over a multi-stage intrusion.

The LSASS benchmark covers one technique in depth. This covers the rest of the
rules in this repo: what each detects across the seven captures, what each
costs on the benign corpus, and what the whole set reports when it is pointed
at an unrelated intrusion it was not written for.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Sequence

from eval import corpus
from eval.classify import DETECTED, analyse
from eval.runner import CompiledRule, load_rules

RULES_DIR = corpus.REPO_ROOT / "rules"
CHAIN_JSON = corpus.REPO_ROOT / "benchmark" / "chain.json"
CHAIN_MD = corpus.REPO_ROOT / "benchmark" / "chain.md"


def own_rules() -> list[CompiledRule]:
    compiled, skipped = load_rules(sorted(RULES_DIR.glob("*.yml")))
    if skipped:
        raise RuntimeError(f"own rules failed to compile: {[s.reason for s in skipped]}")
    return compiled


def technique_of(rule: CompiledRule) -> str:
    for tag in sorted(rule.tags):
        lowered = tag.lower()
        if lowered.startswith("attack.t"):
            return lowered.split(".", 1)[1].upper()
    return "unmapped"


def across_campaigns(rules: Sequence[CompiledRule]) -> dict:
    out = {}
    for capture in corpus.campaigns():
        diagnostics, samples, total = analyse(rules, corpus.events(capture))
        out[capture.id] = {
            "tool": capture.tool,
            "events": total,
            "detected": [r.id for r in rules if diagnostics[r.id].matched],
            "matches": {r.id: diagnostics[r.id].matched for r in rules},
        }
    return out


def across_benign(rules: Sequence[CompiledRule]) -> dict:
    """Cost of the whole rule set on captures without the technique.

    Scoped per rule: each is measured against the captures that are benign for
    its own technique, so a T1055 rule is not charged for firing on a T1055
    capture.
    """
    per_rule = {}
    for rule in rules:
        technique = technique_of(rule)
        captures = corpus.benign_for(technique)
        fires = 0
        events = 0
        hit: list[str] = []
        for capture in captures:
            diagnostics, _, total = analyse([rule], corpus.events(capture), sample_limit=1)
            events += total
            if diagnostics[rule.id].matched:
                fires += diagnostics[rule.id].matched
                hit.append(capture.id)
        per_rule[rule.id] = {
            "technique": technique,
            "captures": len(captures),
            "events": events,
            "fires": fires,
            "per_100k": round(fires * 100000 / events, 3) if events else 0,
            "captures_hit": hit,
        }
    return per_rule


def across_intrusion(rules: Sequence[CompiledRule]) -> dict:
    """Point the rule set at APT29 and report what it says.

    None of these rules was written for this intrusion. Whatever fires here
    fires because the behaviour it targets was present, and whatever stays
    quiet is a gap worth naming.
    """
    out = {}
    for capture in corpus.chain_captures():
        try:
            diagnostics, samples, total = analyse(rules, corpus.events(capture))
        except (corpus.CorpusError, OSError) as exc:
            out[capture.id] = {"error": str(exc)}
            continue
        fired = {}
        for rule in rules:
            if diagnostics[rule.id].matched:
                hosts = Counter(
                    str(e.get("Hostname", "unknown")) for e in samples[rule.id]
                )
                fired[rule.id] = {
                    "matches": diagnostics[rule.id].matched,
                    "hosts": sorted(hosts),
                }
        out[capture.id] = {"events": total, "fired": fired}
    return out


def markdown(results: dict, titles: dict[str, str]) -> str:
    campaigns = results["campaigns"]
    capture_ids = list(campaigns)
    tools = [campaigns[c]["tool"] for c in capture_ids]

    lines = [
        "# Chain results",
        "",
        "Rules in this repo, measured across the seven LSASS captures and the "
        "benign corpus. Generated by `python -m eval.chain --run`.",
        "",
        "| rule | technique | " + " | ".join(tools) + " | fp/100k | benign events |",
        "|---|---|" + "---|" * len(tools) + "---|---|",
    ]
    for rule_id, title in titles.items():
        cells = ["y" if rule_id in campaigns[c]["detected"] else "." for c in capture_ids]
        fp = results["benign"][rule_id]
        lines.append(
            f"| {title} | {fp['technique']} | " + " | ".join(cells)
            + f" | {fp['per_100k']} | {fp['events']:,} |"
        )

    lines += ["", "## Against APT29", "",
              "None of these rules was written for this intrusion.", ""]
    for capture_id, entry in results["intrusion"].items():
        if "error" in entry:
            lines += [f"### {capture_id}", "", f"not evaluated: {entry['error']}", ""]
            continue
        lines += [f"### {capture_id} ({entry['events']:,} events)", ""]
        if not entry["fired"]:
            lines += ["Nothing fired.", ""]
            continue
        for rule_id, info in entry["fired"].items():
            lines.append(
                f"- {titles.get(rule_id, rule_id)}: {info['matches']} matches "
                f"on {', '.join(info['hosts'])}"
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="measure the chain rule set")
    parser.add_argument("--run", action="store_true")
    parser.add_argument("--skip-intrusion", action="store_true")
    args = parser.parse_args(argv)
    if not args.run:
        parser.error("pass --run")

    rules = own_rules()
    titles = {r.id: r.title for r in rules}
    results = {
        "campaigns": across_campaigns(rules),
        "benign": across_benign(rules),
        "intrusion": {} if args.skip_intrusion else across_intrusion(rules),
        "titles": titles,
    }
    CHAIN_JSON.write_text(json.dumps(results, indent=2, sort_keys=True) + "\n")
    CHAIN_MD.write_text(markdown(results, titles))

    for rule in rules:
        detected = sum(1 for c in results["campaigns"].values() if rule.id in c["detected"])
        fp = results["benign"][rule.id]
        print(f"{rule.title[:52]:54s} {detected}/7  fp={fp['fires']:4d} "
              f"({fp['per_100k']}/100k over {fp['events']:,})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
